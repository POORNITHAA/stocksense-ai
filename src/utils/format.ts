import { Timestamp } from 'firebase/firestore';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

export function formatINR(value: number, decimals = 2): string {
  const num = Number.isFinite(value) ? value : 0;
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(num);
}

export function formatNumber(value: number, decimals = 0): string {
  const num = Number.isFinite(value) ? value : 0;
  return new Intl.NumberFormat('en-IN', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(num);
}

export function toDate(value: Timestamp | Date | string | null | undefined): Date | null {
  if (!value) return null;
  if (value instanceof Date) return value;
  if (typeof (value as Timestamp).toDate === 'function') {
    return (value as Timestamp).toDate();
  }
  if (typeof value === 'string') {
    const parsed = new Date(value);
    return Number.isNaN(parsed.getTime()) ? null : parsed;
  }
  return null;
}

export function formatDate(
  value: Timestamp | Date | string | null | undefined,
  timezone = 'Asia/Kolkata'
): string {
  const dt = toDate(value);
  if (!dt) return '—';
  return dt.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    timeZone: timezone,
  });
}

export function formatDateTime(
  value: Timestamp | Date | string | null | undefined,
  timezone = 'Asia/Kolkata'
): string {
  const dt = toDate(value);
  if (!dt) return '—';
  return dt.toLocaleString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    timeZone: timezone,
  });
}

export function buildCsvContent(headers: string[], rows: Array<Array<string | number>>): string {
  const escapeCell = (cell: string | number) => {
    const str = String(cell ?? '');
    if (/[",\n\r]/.test(str)) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };
  return [
    headers.map(escapeCell).join(','),
    ...rows.map((row) => row.map(escapeCell).join(',')),
  ].join('\n');
}

export function exportToCsv(filename: string, headers: string[], rows: Array<Array<string | number>>): void {
  const csvContent = buildCsvContent(headers, rows);
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', filename.endsWith('.csv') ? filename : `${filename}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

function sanitizePdfText(value: unknown): string {
  return String(value ?? '')
    .replace(/₹/g, 'INR ')
    .replace(/→/g, '->')
    .replace(/·/g, '|');
}

export function buildReportPdfDocument(params: {
  title: string;
  subtitle: string;
  headers: string[];
  rows: Array<Array<string | number>>;
  summaryLines?: string[];
}): jsPDF {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' });
  doc.setFontSize(16);
  doc.text(sanitizePdfText(`StockSense AI - ${params.title}`), 40, 42);
  doc.setFontSize(10);
  doc.setTextColor(100);
  doc.text(sanitizePdfText(params.subtitle), 40, 60);

  let startY = 78;
  if (params.summaryLines && params.summaryLines.length > 0) {
    doc.setFontSize(9);
    doc.setTextColor(50);
    params.summaryLines.forEach((line, idx) => {
      doc.text(sanitizePdfText(line), 40, startY + idx * 14);
    });
    startY += params.summaryLines.length * 14 + 10;
  }

  autoTable(doc, {
    startY,
    head: [params.headers.map((h) => sanitizePdfText(h))],
    body: params.rows.map((r) => r.map((c) => sanitizePdfText(c))),
    styles: { fontSize: 8.5, cellPadding: 5 },
    headStyles: { fillColor: [15, 23, 42], textColor: [255, 255, 255] },
    alternateRowStyles: { fillColor: [248, 250, 252] },
  });

  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(140);
    doc.text(
      `Generated by StockSense AI | Page ${i} of ${pageCount}`,
      40,
      doc.internal.pageSize.getHeight() - 20
    );
  }

  return doc;
}

export function exportToPdf(params: {
  title: string;
  subtitle: string;
  filename: string;
  headers: string[];
  rows: Array<Array<string | number>>;
  summaryLines?: string[];
}): void {
  const doc = buildReportPdfDocument(params);
  doc.save(params.filename.endsWith('.pdf') ? params.filename : `${params.filename}.pdf`);
}

export async function compressImageFileToDataUrl(file: File, maxDim = 240): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = () => reject(new Error('Failed to read image file.'));
    reader.onload = () => {
      const img = new Image();
      img.onerror = () => reject(new Error('Unsupported image format.'));
      img.onload = () => {
        const scale = Math.min(1, maxDim / Math.max(img.width, img.height));
        const width = Math.max(1, Math.round(img.width * scale));
        const height = Math.max(1, Math.round(img.height * scale));
        const canvas = document.createElement('canvas');
        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          reject(new Error('Canvas context unavailable.'));
          return;
        }
        ctx.drawImage(img, 0, 0, width, height);
        let dataUrl = canvas.toDataURL('image/jpeg', 0.72);
        if (dataUrl.length > 60000) {
          dataUrl = canvas.toDataURL('image/jpeg', 0.52);
        }
        if (dataUrl.length > 60000) {
          reject(new Error('Compressed image still exceeds 60KB limit. Please choose a smaller image.'));
          return;
        }
        resolve(dataUrl);
      };
      img.src = String(reader.result);
    };
    reader.readAsDataURL(file);
  });
}
